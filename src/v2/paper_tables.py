def table_pcam(snap):
    rows = []
    for tier in ["C", "S"]:
        for f in glob.glob(os.path.join(snap, "runs", tier, "c17", "fold*", "*.json")):
            r = json.load(open(f))
            if r.get("phase") != "final":
                continue
            p = (r.get("pcam") or {}).get("id")
            if p:
                rows.append(dict(tier=tier, arm=r["arm"], fold=r["fold"], seed=r["seed"], auroc=p["auroc"]))
    df = pd.DataFrame(rows)
    g = df.groupby(["tier", "arm", "fold"]).auroc.mean().unstack("fold")
    out, nums = {}, {}
    for tier in ["C", "S"]:
        t = g.loc[tier]
        t = t[[not a.startswith("probe_") or a in MAIN_PROBES for a in t.index]]
        res = pd.DataFrame({"mean": t.mean(axis=1), "min": t.min(axis=1)}).sort_values("mean", ascending=False)
        nums[tier] = {a: dict(mean=float(r["mean"]), min=float(r["min"])) for a, r in res.iterrows()}
        out[tier] = res
    arms = order(set(out["C"].index) | set(out["S"].index))
    lines = []
    for a in arms:
        cells = [tex_label(a)]
        for tier in ["C", "S"]:
            if a in out[tier].index:
                cells += [f"{out[tier].loc[a, 'mean']:.3f}", f"{out[tier].loc[a, 'min']:.3f}"]
            else:
                cells += ["--", "--"]
        lines.append(" & ".join(cells) + " \\\\")
    tex = ("% generated by src/v2/paper_tables.py from the pcam field of the frozen run records (ID-val checkpoint)\n"
           "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}}lrrrr@{}}\n\\toprule\n"
           " & \\multicolumn{2}{c}{Compact tier} & \\multicolumn{2}{c}{Standard tier} \\\\\n"
           "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
           "Arm & mean & min over folds & mean & min over folds \\\\\n\\midrule\n"
           + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular*}\n")
    return tex, nums


# ---------------------------------------------------------------------------------------------------------------
def interaction(an):
    nums = {}
    for c in COHORTS:
        a = load(an, "C", c, "per_run")
        m = a.groupby(["arm", "domain"]).metric.mean().unstack(0)
        inter = m["simclr_sam"] - m["simclr"] - m["sam"] + m["erm"]
        K = len(inter)
        se = inter.std(ddof=1) / np.sqrt(K)
        t = stats.t.ppf(.975, K - 1)
        nums[c] = dict(K=K, per_domain={k: float(v) for k, v in inter.items()}, mean=float(inter.mean()),
                       ci=[float(inter.mean() - t * se), float(inter.mean() + t * se)],
                       p=float(stats.ttest_1samp(inter, 0).pvalue))
    return nums


def table_response(an):
    """Oldham's correlation of each arm with ERM: sign counts, Pitman-Morgan and exact permutation tests."""
    rows = []
    for tier in ["S", "C"]:
        for c in COHORTS:
            r = load(an, tier, c, "response")
            rows.append(" & ".join([tier if c == "c17" else "", CLABEL[c], str(int(r.K.iloc[0])),
                                    f"{int((r.oldham_r < 0).sum())}/{len(r)}", f"{r.oldham_r.median():+.2f}",
                                    str(int((r.pm_p < 0.05).sum())), f"{r.perm_p.min():.3f}"]) + " \\\\")
        if tier == "S":
            rows.append("\\addlinespace[3pt]")
    head = ("Tier & Cohort & $K$ & $r<0$ & median $r$ & Pitman--Morgan $p<0.05$ & smallest exact $p$ \\\\")
    return ("% generated by src/v2/paper_tables.py from response_id.csv\n"
            "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}}llrrrrr@{}}\n"
            f"\\toprule\n{head}\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular*}\n")


def extra_numbers(an, sens):
    """Numbers quoted in the text that are not in a table."""
    out = {}
    for tier in ["C", "S"]:
        for c in COHORTS:
            pr = load(an, tier, c, "per_run")
            erm = pr[pr.arm == "erm"].groupby("domain").metric
            sm = load(an, tier, c, "summary").set_index("arm")
            rk = load(an, tier, c, "ranks").set_index("arm")
            wd = load(an, tier, c, "summary").worst_domain.value_counts()
            width = rk.rank_worst_domain_ci.map(lambda x: json.loads(x)[1] - json.loads(x)[0])
            width_seed = rk.rank_worst_seed_ci.map(lambda x: json.loads(x)[1] - json.loads(x)[0])
            rs = load(an, tier, c, "response")
            out[f"{tier}/{c}"] = dict(
                erm_seed_range_by_domain={d: [float(g.min()), float(g.max())] for d, g in erm},
                erm_worst=float(sm.loc["erm", "worst"]), erm_worst_domain=sm.loc["erm", "worst_domain"],
                erm_mean=float(sm.loc["erm", "mean"]),
                most_common_worst_domain=[wd.index[0], int(wd.iloc[0]), int(wd.sum())],
                rank_ci_width_domain_median=float(width.median()),
                rank_ci_width_seed_median=float(width_seed.median()),
                pbest_top=[rk.pbest_worst_domain.idxmax(), float(rk.pbest_worst_domain.max())],
                ece_erm=float(sm.loc["erm", "ece_mean"]),
                ece_best=[sm.ece_mean.idxmin(), float(sm.ece_mean.min())],
                ece_tia_vs_jitter=[float(sm.loc["tia_style", "ece_mean"]), float(sm.loc["he_jitter", "ece_mean"])],
                oldham_negative=int((rs.oldham_r < 0).sum()), n_response=len(rs),
                pm_p_lt05=int((rs.pm_p < 0.05).sum()), perm_p_lt05=int((rs.perm_p < 0.05).sum()),
                perm_p_min=float(rs.perm_p.min()))
    # agreement between the tiers for the arms run at both
    for c in COHORTS:
        a = load(an, "C", c, "summary").set_index("arm")["worst"]
        b = load(an, "S", c, "summary").set_index("arm")["worst"]
        common = sorted(set(a.index) & set(b.index))
        out[f"tier_tau/{c}"] = dict(n=len(common), tau=float(stats.kendalltau(a[common], b[common]).statistic),
                                    arms=common)
    # MIDOG 2021 scale-normalization sensitivity (compact tier)
    f = os.path.join(sens, "C", "midog21", "summary_id.csv")
    if os.path.exists(f):
        u = pd.read_csv(f).set_index("arm")
        n = load(an, "C", "midog21sn", "summary").set_index("arm")
        common = sorted(set(u.index) & set(n.index))
        out["midog21_sens"] = dict(
            n=len(common),
            tau_worst=float(stats.kendalltau(n.loc[common, "worst"], u.loc[common, "worst"]).statistic),
            tau_mean=float(stats.kendalltau(n.loc[common, "mean"], u.loc[common, "mean"]).statistic),
            erm=[float(n.loc["erm", "worst"]), float(u.loc["erm", "worst"])],
            max_abs_worst_change=float((n.loc[common, "worst"] - u.loc[common, "worst"]).abs().max()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/v2/analysis")
    ap.add_argument("--snap", default=os.path.join(os.environ.get("HISTOPATH_DATA", "data"), "v2/snap_final2_20261005"))
    ap.add_argument("--out", default="paper/media/tables")
    ap.add_argument("--sens", default="results/v2/analysis_sens")
    ap.add_argument("--numbers", default="results/v2/analysis/paper_numbers.json")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    nums = {}
    for tier in ["S", "C"]:
        tex, n = table_main(a.analysis, tier)
        open(os.path.join(a.out, f"tab_main_{tier}.tex"), "w").write(tex)
        nums[f"n_arms_{tier}"] = n
    tex, nums["evidence"] = table_evidence(a.analysis)
    open(os.path.join(a.out, "tab_evidence.tex"), "w").write(tex)
    tex, nums["selection"] = table_selection(a.analysis)
    open(os.path.join(a.out, "tab_selection.tex"), "w").write(tex)
    tex, nums["pcam"] = table_pcam(a.snap)
    open(os.path.join(a.out, "tab_pcam.tex"), "w").write(tex)
    nums["simclr_sam_interaction_C"] = interaction(a.analysis)
    open(os.path.join(a.out, "tab_response.tex"), "w").write(table_response(a.analysis))
    nums["extra"] = extra_numbers(a.analysis, a.sens)
    json.dump(nums, open(a.numbers, "w"), indent=1)
    print("wrote", sorted(os.listdir(a.out)), "and", a.numbers)


if __name__ == "__main__":
    main()
