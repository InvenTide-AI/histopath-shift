def table_selection(an):
    rows, nums = [], {}
    for tier in ["S", "C"]:
        for c in COHORTS:
            sels = [s for s in ["id", "ood", "last", "oracle"]
                    if os.path.exists(os.path.join(an, tier, c, f"summary_{s}.csv"))]
            S = {s: load(an, tier, c, "summary", s).set_index("arm")["worst"] for s in sels}
            common = sorted(set.intersection(*[set(x.index) for x in S.values()]))
            cells = [tier if c == "c17" else "", CLABEL[c], str(len(common))]
            d = {"n_common": len(common)}
            for s in ["ood", "last", "oracle"]:
                if s in S:
                    tau = stats.kendalltau(S["id"][common], S[s][common]).statistic
                    cells.append(f"{tau:.2f}")
                    d[f"tau_{s}"] = float(tau)
                else:
                    cells.append("--")
            tops = []
            for s in ["id", "ood", "last", "oracle"]:
                if s in S:
                    t = S[s][common].idxmax()
                    d[f"top_{s}"] = t
                    tops.append(t)
            same = len(set(tops)) == 1
            d["same_top"] = same
            cells.append("yes" if same else "no")
            nums[f"{tier}/{c}"] = d
            rows.append(" & ".join(cells) + " \\\\")
        if tier == "S":
            rows.append("\\addlinespace[3pt]")
    head = ("Tier & Cohort & Arms & $\\tau_b$ OOD-val & $\\tau_b$ last & $\\tau_b$ oracle & Same top arm \\\\")
    tex = ("% generated by src/v2/paper_tables.py from summary_{id,ood,last,oracle}.csv (worst-domain AUROC)\n"
           "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}}llrrrrl@{}}\n"
           f"\\toprule\n{head}\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular*}\n")
    return tex, nums


