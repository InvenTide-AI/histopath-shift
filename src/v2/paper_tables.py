"""Emit the manuscript tables (paper/media/tables/*.tex) and a numbers file from the frozen analysis.

Every number in these tables is read from results/v2/analysis/{C,S}/... (snapshot 1381bdd759f9), except the
PatchCamelyon table, which is read from the `pcam` field of the frozen run records, and the SimCLR x SAM interaction,
which is computed from per_run_id.csv. Nothing is typed by hand.

    python src/v2/paper_tables.py --analysis results/v2/analysis --snap $V2/snap_final2_20261005 \
        --out paper/media/tables --numbers results/v2/analysis/paper_numbers.json
"""
import argparse
import glob
import json
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_figures_v2 import ARM_LABEL, ARM_ORDER, TTA_LABEL, TRANSDUCTIVE, family  # noqa: E402

COHORTS = ["c17", "canine", "midog21sn", "midogpp"]
CLABEL = {"c17": "Camelyon17", "canine": "Canine cSCC", "midog21sn": "MIDOG 2021", "midogpp": "MIDOG++"}
CSHORT = {"c17": "C17", "canine": "Canine", "midog21sn": "MIDOG21", "midogpp": "MIDOG++"}
SEEDS = {"C": 5, "S": 3}
FAMILY_TEX = {0: "Reference and controls", 1: "Domain-aware training", 2: "Stain normalization and color",
              3: "Self-supervision", 4: "Sharpness-aware", 5: "Test-time adaptation",
              6: "Pretrained representations"}
FAMILY_ORDER = [0, 1, 2, 3, 4, 5, 6]
MAIN_PROBES = ("probe_resnet50_imagenet", "probe_resnet50_lunit_bt", "probe_vit_s16_lunit_dino")  # ladder probes go to the ladder figure


def tex_label(arm):
    if "@" in arm:
        t, a = arm.split("@", 1)
        return f"{TTA_LABEL.get(t, t)} ({tex_label(a)})".replace("$^{\\dagger}$", "") + "$^{\\dagger}$"
    lab = ARM_LABEL.get(arm, arm).replace("&", "\\&")
    return lab + ("$^{\\dagger}$" if arm in TRANSDUCTIVE else "")


def order(arms):
    def key(a):
        idx = ARM_ORDER.index(a) if a in ARM_ORDER else len(ARM_ORDER)
        return (FAMILY_ORDER.index(family(a)), idx, a)
    return sorted(arms, key=key)


def load(an, tier, cohort, kind, sel="id"):
    return pd.read_csv(os.path.join(an, tier, cohort, f"{kind}_{sel}.csv"))


# ---------------------------------------------------------------------------------------------------------------
def table_main(an, tier):
    """Worst-domain AUROC (rank) and mean AUROC per arm and cohort, ID-val selection."""
    S = {c: load(an, tier, c, "summary").set_index("arm") for c in COHORTS}
    R = {c: load(an, tier, c, "ranks").set_index("arm") for c in COHORTS}
    arms = order(set().union(*[set(S[c].index) for c in COHORTS]))
    best = {c: S[c]["worst"].max() for c in COHORTS}
    n_arms = {c: len(S[c]) for c in COHORTS}
    lines = []
    fam_prev = None
    for a in arms:
        fam = family(a)
        if fam != fam_prev:
            if fam_prev is not None:
                lines.append("\\addlinespace[2pt]")
            lines.append(f"\\multicolumn{{9}}{{@{{}}l}}{{\\emph{{{FAMILY_TEX[fam]}}}}}\\\\")
            fam_prev = fam
        cells = [tex_label(a)]
        for c in COHORTS:
            if a not in S[c].index:
                cells += ["--", "--"]
                continue
            w, m, rk = S[c].loc[a, "worst"], S[c].loc[a, "mean"], int(R[c].loc[a, "rank_worst"])
            ws = f"{w:.3f}"
            if abs(w - best[c]) < 1e-12:
                ws = f"\\textbf{{{ws}}}"
            cells += [f"{ws} ({rk})", f"{m:.3f}"]
        lines.append(" & ".join(cells) + " \\\\")
    head = " & ".join(["Arm"] + [f"\\multicolumn{{2}}{{c}}{{{CLABEL[c]} ($K={int(S[c]['K'].iloc[0])}$)}}"
                                 for c in COHORTS]) + " \\\\"
    cmid = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(4))
    sub = " & " + " & ".join(["worst (rank)", "mean"] * 4) + " \\\\"
    body = "\n".join(lines)
    return (f"% generated by src/v2/paper_tables.py from results/v2/analysis/{tier}/*/summary_id.csv, ranks_id.csv\n"
            "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}}l*{4}{rr}@{}}\n\\toprule\n"
            f"{head}\n{cmid}\n{sub}\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular*}}\n"), \
        {c: n_arms[c] for c in COHORTS}


