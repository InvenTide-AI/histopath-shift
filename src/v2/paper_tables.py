def table_evidence(an):
    """Per tier and cohort: variance shares, contrasts against ERM and the K needed for a 0.05 gain."""
    rows, nums = [], {}
    for tier in ["S", "C"]:
        s = SEEDS[tier]
        for c in COHORTS:
            v = load(an, tier, c, "variance")
            ct = load(an, tier, c, "contrasts")
            p = load(an, tier, c, "power")
            p = p[p.ref == "erm"]
            K = int(ct.K.iloc[0])
            p0 = p[(p.seeds == s) & (p.rho == 0) & (p.delta == 0.05)]
            p5 = p[(p.seeds == s) & (p.rho == 0.5) & (p.keff_mode == "ratio") & (p.delta == 0.05)]
            erm = v[v.arm == "erm"].iloc[0]
            up = int(((ct.p < 0.05) & (ct.mean_diff > 0)).sum())
            dn = int(((ct.p < 0.05) & (ct.mean_diff < 0)).sum())
            hu = int(((ct.p_holm < 0.05) & (ct.mean_diff > 0)).sum())
            hd = int(((ct.p_holm < 0.05) & (ct.mean_diff < 0)).sum())
            top = ct.sort_values("mean_diff", ascending=False).iloc[0]
            d = dict(K=K, seeds=s, n_arms=len(ct), icc_median=float(v.icc_anova.median()),
                     icc_q1=float(v.icc_anova.quantile(.25)), icc_q3=float(v.icc_anova.quantile(.75)),
                     icc_lo_gt_half=int((v.icc_ci_lo > 0.5).sum()), icc_lo_zero=int((v.icc_ci_lo <= 0).sum()),
                     erm_icc=float(erm.icc_anova), erm_icc_ci=[float(erm.icc_ci_lo), float(erm.icc_ci_hi)],
                     erm_sd_domain=float(erm.sigma_domain_anova), erm_sd_run=float(erm.sigma_run_anova),
                     raw_up=up, raw_down=dn, holm_up=hu, holm_down=hd,
                     top_arm=top.arm, top_gain=float(top.mean_diff), top_n_improved=int(top.n_improved),
                     sd_delta_median=float(p0.sd_delta.median()),
                     # a required number of domains is rounded up (the median of an even count can be x.5)
                     kmin05_median=float(np.ceil(p0.K_min.median())),
                     kmin05_rho05_median=float(np.ceil(p5.K_min.median())))
            nums[f"{tier}/{c}"] = d
            rows.append(" & ".join([
                tier if c == "c17" else "", CSHORT[c], str(K),
                f"{d['icc_median']:.2f} [{d['icc_q1']:.2f}, {d['icc_q3']:.2f}]",
                f"{d['icc_lo_gt_half']}/{len(v)}",
                f"{d['erm_sd_domain']:.3f} / {d['erm_sd_run']:.3f}",
                f"{up} / {dn}", f"{hu} / {hd}",
                f"{tex_label(top.arm)} ({top.mean_diff:+.3f})",
                f"{d['sd_delta_median']:.3f}", f"{d['kmin05_median']:.0f} ({d['kmin05_rho05_median']:.0f})"]) + " \\\\")
        if tier == "S":
            rows.append("\\addlinespace[3pt]")
    body = "\n".join(rows)
    head = ("Tier & Cohort & $K$ & ICC median [IQR] & CI$_{\\text{lo}}>0.5$ & ERM $\\hat\\sigma_D$ / $\\hat\\sigma_R$"
            " & $p<0.05$ ($+$/$-$) & Holm ($+$/$-$) & Largest gain over ERM & $\\hat\\sigma_\\Delta$"
            " & $K_{0.05}$ \\\\")
    tex = ("% generated by src/v2/paper_tables.py from variance_id.csv, contrasts_id.csv, power_id.csv\n"
           "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}}llrlrlrr>{\\raggedright\\arraybackslash}p{2.2cm}rr@{}}\n"
           f"\\toprule\n{head}\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular*}}\n")
    return tex, nums


